  function closeOtherSections(skip) {
    if (skip !== 'about') { state.about = false; document.getElementById("menu-about").classList.remove("expanded-about"); }
    if (skip !== 'portfolio') { state.portfolio = false; document.getElementById("menu-portfolio").classList.remove("expanded-portfolio"); }
    if (skip !== 'contact') { state.contact = false; document.getElementById("menu-contact").classList.remove("expanded-contact"); }
  }

  function closeAllSections() {
    closeOtherSections(null);
  }

  function openLightbox(i) {
    var p = projects[i];
    state.lightbox.project = p;
    state.lightbox.index = 0;
    document.getElementById("lightbox-title").textContent = p.title;
    document.getElementById("lightbox-category").textContent = p.category;
    document.getElementById("lightbox-desc").textContent = p.description;
    updateLightboxImage();
    document.getElementById("lightbox").classList.add("active");
    document.body.style.overflow = "hidden";
    preloadAdjacent();
  }

  function closeLightbox() {
    document.getElementById("lightbox").classList.remove("active");
    document.body.style.overflow = "";
    state.lightbox.project = null;
  }

  function updateLightboxImage() {
    var p = state.lightbox.project;
    if (!p) return;
    var img = document.getElementById("lightbox-image");
    img.style.opacity = "0";
    setTimeout(function () {
      img.src = p.images[state.lightbox.index];
      img.alt = p.title + " — " + (state.lightbox.index + 1);
      img.onload = function () { img.style.opacity = "1"; };
    }, 120);
    document.getElementById("lightbox-counter").textContent =
      (state.lightbox.index + 1) + " / " + p.images.length;
  }

  function preloadAdjacent() {
    var p = state.lightbox.project;
    if (!p) return;
    var len = p.images.length;
    var next = (state.lightbox.index + 1) % len;
    var prev = (state.lightbox.index - 1 + len) % len;
    new Image().src = p.images[next];
    new Image().src = p.images[prev];
  }

  function lightboxNav(dir) {
    if (!state.lightbox.project) return;
    var len = state.lightbox.project.images.length;
    state.lightbox.index = (state.lightbox.index + dir + len) % len;
    updateLightboxImage();
    preloadAdjacent();
  }

  function initLightbox() {
    document.getElementById("lightbox-close").addEventListener("click", closeLightbox);
    document.getElementById("lightbox-prev").addEventListener("click", function () { lightboxNav(-1); });
    document.getElementById("lightbox-next").addEventListener("click", function () { lightboxNav(1); });
    document.getElementById("lightbox").addEventListener("click", function (e) {
      if (e.target === this) closeLightbox();
    });

    document.addEventListener("keydown", function (e) {
      if (!document.getElementById("lightbox").classList.contains("active")) return;
      if (e.key === "Escape") closeLightbox();
      if (e.key === "ArrowLeft") lightboxNav(-1);
      if (e.key === "ArrowRight") lightboxNav(1);
    });

    var touchX = 0;
    var lb = document.getElementById("lightbox");
    lb.addEventListener("touchstart", function (e) { touchX = e.changedTouches[0].screenX; }, { passive: true });
    lb.addEventListener("touchend", function (e) {
      var diff = touchX - e.changedTouches[0].screenX;
      if (Math.abs(diff) > 50) lightboxNav(diff > 0 ? 1 : -1);
    }, { passive: true });
  }

  function initSmoothScroll() {
    document.querySelectorAll('a[href^="#"]').forEach(function (link) {
      link.addEventListener("click", function (e) {
        var target = document.querySelector(this.getAttribute("href"));
        if (target) {
          e.preventDefault();
          target.scrollIntoView({ behavior: "smooth" });
        }
      });
    });
  }

  document.addEventListener("DOMContentLoaded", function () {
    buildCarousel();
    initCursorGlow();
    initHeroEyes();
    initAbout();
    initPortfolio();
    initContact();
    initLightbox();
    initSmoothScroll();
  });
